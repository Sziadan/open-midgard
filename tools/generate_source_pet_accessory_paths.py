from __future__ import annotations

import argparse
import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BINARY = ROOT / "HighPriest.exe"
SOURCE = ROOT / "Ref/Session2.cpp"
GENERATED = ROOT / "src/core/SourcePetAccessoryPaths.generated.inc"
EXPECTED_BINARY_SHA256 = "9ABC36C88376387D85C878C0C879D9AF8EF66EB1F5152638085DC6995E3F4742"
FUNCTION_VA = 0x680980
FUNCTION_END_VA = 0x680A4F  # exclusive; includes the final ret 4 and ends before jump table
FUNCTION_SHA256 = "6e9766ceb3ab6acd18042e5ffafd1f9f496b1c59b58047c1befeecb5cc4fbb3f"
JUMP_TABLE_VA = 0x680A50
JUMP_TARGETS = [
    0x68099B, 0x680A46, 0x6809A4, 0x6809AD, 0x6809B6,
    0x6809BF, 0x6809C8, 0x6809D1, 0x6809DA, 0x6809E3,
    0x6809EC, 0x6809F5, 0x6809FE, 0x680A07, 0x680A10,
    0x680A19, 0x680A22, 0x680A2B, 0x680A34, 0x680A3D,
]


def fail(message: str) -> None:
    raise ValueError(message)


def import_pe_readers():
    sys.path.insert(0, str(ROOT / "tools"))
    from generate_source_command_list_tables import read_pe_region, read_pe_va
    return read_pe_region, read_pe_va


def parse_switch(source: str) -> dict[int, int]:
    marker = "char *__thiscall CSession::GetPetAccActName(CSession *this, int accId)"
    begin = source.find(marker)
    end = source.find("char *__thiscall CSession::GetPetActText", begin + len(marker))
    if begin < 0 or end < 0:
        fail("could not isolate Ref CSession::GetPetAccActName body")
    body = source[begin:end]
    sig = source.rfind("// Decompiled from address: 0x680980", 0, begin)
    if sig < 0:
        fail("source function address is not 0x680980")

    rows = {int(item_id): int(literal_va, 16) for item_id, literal_va in re.findall(
        r"case\s+(\d+):\s*result\s*=\s*\(char \*\)&unk_([0-9A-Fa-f]+);", body)}
    default = re.search(r"default:\s*result\s*=\s*\(char \*\)&unk_([0-9A-Fa-f]+);", body)
    if not default:
        fail("source switch has no default literal")
    expected_ids = [10001, *range(10003, 10021)]
    if sorted(rows) != expected_ids:
        fail(f"source switch case IDs changed: {sorted(rows)}")
    if len(rows) != 19:
        fail(f"source switch has duplicate or missing cases: {len(rows)}")
    rows[-1] = int(default.group(1), 16)
    return rows


def validate_pe(binary: bytes, read_pe_region, read_pe_va, rows: dict[int, int]) -> None:
    digest = hashlib.sha256(binary).hexdigest().upper()
    if digest != EXPECTED_BINARY_SHA256:
        fail(f"selected PE SHA-256 mismatch: {digest}")

    function = read_pe_region(binary, FUNCTION_VA)[:FUNCTION_END_VA - FUNCTION_VA]
    if len(function) != FUNCTION_END_VA - FUNCTION_VA:
        fail("selected PE function extent is truncated")
    if hashlib.sha256(function).hexdigest() != FUNCTION_SHA256:
        fail("selected PE GetPetAccActName function bytes do not match reviewed bounds/hash")
    if function[:3] != bytes.fromhex("558bec") or function[-3:] != bytes.fromhex("c20400"):
        fail("selected PE GetPetAccActName prologue/epilogue mismatch")

    import struct
    targets = list(struct.unpack("<20I", read_pe_region(binary, JUMP_TABLE_VA)[:80]))
    if targets != JUMP_TARGETS:
        fail("selected PE GetPetAccActName jump table targets changed")

    ids = list(range(10001, 10021))
    for item_id, target in zip(ids, targets, strict=True):
        expected_va = rows.get(item_id, rows[-1])
        code = read_pe_region(binary, target)
        if code[:1] != b"\xB8" or len(code) < 8 or code[5:8] != b"\x5D\xC2\x04":
            fail(f"selected PE case {item_id} is not a return-literal case at 0x{target:08x}")
        returned_va = struct.unpack_from("<I", code, 1)[0]
        if returned_va != expected_va:
            fail(f"selected PE case {item_id} returns 0x{returned_va:08x}, source maps to 0x{expected_va:08x}")
        if read_pe_va(binary, expected_va) == b"":
            fail(f"selected PE literal for case {item_id} is empty")


def byte_string(data: bytes) -> str:
    # Three-digit octal escapes retain each exact byte regardless of source-code page.
    return '"' + "".join(f"\\{byte:03o}" for byte in data) + '"'


def render(binary: bytes, read_pe_va, rows: dict[int, int]) -> str:
    lines = [
        "// Generated by tools/generate_source_pet_accessory_paths.py; do not edit.",
        f"// Source: Ref/Session2.cpp CSession::GetPetAccActName; PE SHA-256 {EXPECTED_BINARY_SHA256}.",
        "// Values are the selected PE's exact NUL-terminated path bytes (CP949); default sentinel -1 also covers item 10002.",
        "struct SourcePetAccessoryPath { int itemId; const char* path; };",
        "constexpr SourcePetAccessoryPath kSourcePetAccessoryPaths[] = {",
    ]
    for item_id in [10001, *range(10003, 10021), -1]:
        literal_va = rows[item_id]
        raw = read_pe_va(binary, literal_va)
        lines.append(f"    {{{item_id}, {byte_string(raw)}}}, // VA 0x{literal_va:08X}")
    lines.extend(["};", ""])
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate selected-PE pet accessory ACT paths.")
    parser.add_argument("--check", action="store_true", help="validate source/PE provenance and generated file without writing")
    args = parser.parse_args()
    try:
        read_pe_region, read_pe_va = import_pe_readers()
        binary = BINARY.read_bytes()
        rows = parse_switch(SOURCE.read_text(encoding="utf-8"))
        validate_pe(binary, read_pe_region, read_pe_va, rows)
        expected = render(binary, read_pe_va, rows)
        if args.check:
            if not GENERATED.exists() or GENERATED.read_text(encoding="ascii") != expected:
                fail(f"{GENERATED.relative_to(ROOT)} is stale; run {Path(__file__).name}")
            print("source pet accessory paths: source switch, selected PE provenance, and generated file are current")
        else:
            GENERATED.write_text(expected, encoding="ascii", newline="\n")
            print(f"wrote {GENERATED.relative_to(ROOT)}")
        return 0
    except (OSError, ValueError, KeyError, TypeError, UnicodeError) as exc:
        print(f"source pet accessory path generation failed: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
