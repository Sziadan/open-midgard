"""Regenerate the embedded reader; esbuild is a developer tool, not a dependency."""
import argparse
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--esbuild", required=True, help="Path to esbuild 0.25.12 executable")
args = parser.parse_args()
with tempfile.TemporaryDirectory() as directory:
    bundle = Path(directory) / "reader.js"
    subprocess.run([args.esbuild, str(root / "third_party/gr2-reader/client.js"),
                    "--bundle", "--format=iife", "--global-name=OpenGr2Reader",
                    "--define:process=undefined", "--minify", "--target=es2017",
                    "--log-level=error", "--outfile=" + str(bundle)], check=True)
    script = (root / "third_party/gr2-reader/qt-compat.js").read_text() + "\n" + bundle.read_text()
    assert ')GR2SCRIPT"' not in script
    (root / "src/res/Gr2Reader.generated.h").write_text(
        '// Generated by tools/build_gr2_reader.py; do not edit.\n'
        '// MIT notices: third_party/gr2-reader/LICENSE.\n#pragma once\n'
        'static constexpr const char kGr2ReaderScript[] = R"GR2SCRIPT(' + script + ')GR2SCRIPT";\n',
        encoding="utf-8")
