"""Export the selected client's skill identifiers without changing UI metadata.

Verify every primary initializer assignment against its selected-PE store,
including duplicate writes and placeholder aliases. Never execute the client.
"""
import argparse
import ast
import hashlib
import json
from pathlib import Path
import re
import shutil
import struct
import subprocess

ROOT=Path(__file__).resolve().parents[1]
FAMILIES=(('Player','InitTable','s_skillIdNameList',0,1039,0x516400,0x51900a,0x78c668),
          ('Guild','InitGuildTable','s_guildSkillIdNameList',10000,16,0x515f00,0x516050,0x78c678),
          ('Homun','InitHomunTable','s_homunSkillIdNameList',8000,17,0x516050,0x5161a0,0x78c658),
          ('Merc','InitMerTable','s_merSkillIdNameList',8200,38,0x5161a0,0x516400,0x78c630))

def body(text,signature):
    start=text.index('{',text.index(signature));depth=0
    for end in range(start,len(text)):
        depth+=(text[end]=='{')-(text[end]=='}')
        if not depth:return text[start:end+1]
    raise ValueError(signature)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--exe',type=Path,default=ROOT/'HighPriest.exe')
    parser.add_argument('--objdump',default=shutil.which('objdump') or 'C:/Qt/Tools/mingw1310_64/bin/objdump.exe')
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--report',type=Path)
    args=parser.parse_args();data=args.exe.read_bytes()
    assert hashlib.sha256(data).hexdigest()=='9abc36c88376387d85c878c0c879d9af8ef66eb1f5152638085dc6995e3f4742'
    pe=struct.unpack_from('<I',data,0x3c)[0];section=pe+24+struct.unpack_from('<H',data,pe+20)[0]
    def at(va,n):
        rva=va-0x400000
        for i in range(struct.unpack_from('<H',data,pe+6)[0]):
            size,start,raw_size,raw=struct.unpack_from('<IIII',data,section+i*40+8)
            if start<=rva<start+max(size,raw_size):return data[raw+rva-start:raw+rva-start+n]
        raise ValueError(hex(va))
    def cstr(va):return at(va,256).split(b'\0')[0].decode('ascii')
    assert at(0x4b31d3,9)==bytes.fromhex('8b41048b4d088d0488')
    ref=(ROOT/'Ref/SkillInfo.cpp').read_text(errors='replace')
    dump=(ROOT/'HighPriest.exe.c').read_text(errors='replace')
    literals={name:ast.literal_eval(value) for name,value in re.findall(r'^char\s+(\w+)\[\d+\]\s*=\s*("(?:\\.|[^"\\])*");',dump,re.M)}
    output=['// Generated by tools/gen_source_skill_names.py; selected PE9ABC36C8.',
            '// Backend identifiers only. Preserve primary placeholders and duplicate-key aliases.']
    report={'selected_binary_sha256':hashlib.sha256(data).hexdigest(),'families':{}}
    for family,method,table,base,count,start,end,vector in FAMILIES:
        source=body(ref,f'void __cdecl SKILL_INFO::{method}()')
        default=literals[re.search(r'_X = (\w+);',source)[1]];expected=[]
        for line in source.splitlines():
            if f'SKILL_INFO::{table}' not in line:continue
            symbol=re.search(r'= (\w+);',line)
            if not symbol:continue
            if 'operator[]' in line:index=int(re.search(r',\s*(0x[\da-fA-F]+|\d+)u?\)',line)[1],0)
            elif '_First +' in line:index=int(re.search(r'_First \+ (\d+)\)',line)[1])
            elif f'*SKILL_INFO::{table}._First =' in line:index=0
            else:continue
            expected.append((index,literals[symbol[1]]))
        assembly=subprocess.check_output([args.objdump,'-d',f'--start-address={start}',f'--stop-address={end}',str(args.exe)],text=True)
        regs={};argument=None;actual=[];default_seen=False
        for line in assembly.splitlines():
            match=re.match(r'\s*([\da-f]+):\s+(?:[\da-f]{2}\s+)+\s*([a-z]+)\s*(.*)',line)
            if not match:continue
            va=int(match[1],16);op=match[2];operands=match[3].split('#')[0].strip()
            for literal_va in re.findall(r'\$0x([\da-f]+)',operands):
                try:default_seen|=cstr(int(literal_va,16))==default
                except (ValueError,UnicodeDecodeError):pass
            if op=='ret':break
            if op=='push':
                arg=re.fullmatch(r'\$0x([\da-f]+)',operands);argument=int(arg[1],16) if arg else None
            elif op=='call':
                target=int(operands.split()[0],16)
                pointer=regs.get('ecx') if target==0x4b31d0 else None
                regs.update(eax=('ptr',argument) if pointer==('vector',0) and argument is not None else None,ecx=None,edx=None)
                argument=None
            elif op in ('mov','movl'):
                store=re.fullmatch(r'(\$0x[\da-f]+|%\w+),(?:(0x[\da-f]+))?\(%(\w+)\)',operands)
                if store and (regs.get(store[3]) or (None,))[0]=='ptr':
                    pointer=regs[store[3]];offset=int(store[2] or '0',16)
                    assert offset%4==0
                    literal=('imm',int(store[1][1:],16)) if store[1].startswith('$') else regs.get(store[1][1:])
                    assert literal and literal[0]=='imm',(family,hex(va),'unknown string register')
                    actual.append((pointer[1]+offset//4,cstr(literal[1]),va))
                destination=re.search(r',%(\w+)$',operands)
                if destination:
                    src=operands.split(',')[0];value=None
                    if src==hex(vector+4):value=('ptr',0)
                    elif src=='$'+hex(vector):value=('vector',0)
                    elif src.startswith('$0x'):value=('imm',int(src[1:],16))
                    elif src.startswith('%'):value=regs.get(src[1:])
                    regs[destination[1]]=value
            elif (destination:=re.search(r',%(\w+)$',operands)):
                regs[destination[1]]=None
        assert default_seen,(family,'missing default literal')
        assert [(i,text) for i,text,_ in actual]==expected,(family,len(actual),len(expected),'selected assignment order differs')
        expected_final=dict(expected);actual_final={i:text for i,text,_ in actual}
        assert actual_final==expected_final,(family,len(actual_final),len(expected_final),
            [(i,text,actual_final.get(i)) for i,text in expected_final.items() if actual_final.get(i)!=text][:5])
        values=[default]*count
        for index,text,_ in actual:
            assert 0<=index<count;values[index]=text
        output.append(f'static constexpr const char* kSource{family}SkillNames[] = {{')
        output.extend('    '+json.dumps(value)+',' for value in values)
        output.append('};')
        report['families'][family]={'base':base,'count':count,'default':default,'verified_stores':len(actual),
            'stores':[{'index':i,'name':text,'va':hex(va)} for i,text,va in actual]}
    generated='\n'.join(output)+'\n';path=ROOT/'src/skill/SourceSkillNames.inc'
    if args.check:assert path.read_text()==generated,'generated source names are stale'
    else:path.write_text(generated)
    if args.report:args.report.write_text(json.dumps(report,indent=2)+'\n')
    print('Selected primary skill-name stores/defaults verified; generated backend tables '+('match' if args.check else 'written'))

if __name__=='__main__':main()
